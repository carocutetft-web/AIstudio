// Rebalanced economy: strictly limit gems from achievements
export const ACHIEVEMENTS: Achievement[] = RAW_ACHIEVEMENTS.map((ach) => {
  let gems = 0;
  if (ach.tier === 'diamond') {
    gems = 3;
  } else if (ach.tier === 'platinum') {
    gems = 2;
  } else if (ach.tier === 'gold') {
    gems = 1;
  } else if (ach.tier === 'silver' && (ach.id.endsWith('_100') || ach.id.endsWith('_max') || ach.id.includes('master') || ach.id.endsWith('_25'))) {
    // only select milestone silver achievements give 1 gem
    gems = 1;
  } else {
    gems = 0; // all bronze & early silver give zero gems
  }
  return {
    ...ach,
    rewardGems: gems,
  };
});

